#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the human-readable mirror of the Chinese case set.

Input : cases/zh/test_cases.json   (authoritative)
Output: cases/zh/test_cases_human_readable.md

The mirror restates, for every case, the case metadata and the 12 user turns
verbatim. It adds no content and is never edited by hand: re-run this script
after any change to the JSON.

Usage (from the repository root):
    python code/tools/generate_zh_cases_md.py           # (re)write the mirror
    python code/tools/generate_zh_cases_md.py --check   # fail if the mirror is stale

License: MIT.
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "cases" / "zh" / "test_cases.json"
OUT = ROOT / "cases" / "zh" / "test_cases_human_readable.md"


def render(data: dict) -> str:
    meta = data.get("metadata", {})
    cases = data["cases"]
    n_turns = len(cases[0]["prompts"]) if cases else 0

    out: list[str] = []
    out.append("# Echo-Bench — Chinese case set (human-readable mirror)")
    out.append("")
    out.append("> **Auto-generated from [`test_cases.json`](test_cases.json); do not edit this file.**")
    out.append("> The JSON is authoritative. Regenerate from the repository root with")
    out.append("> `python code/tools/generate_zh_cases_md.py`; verify with `--check`.")
    out.append("")
    out.append(f"Source: `test_cases.json`, version `{data.get('version', '')}` — "
               f"{len(cases)} cases × {n_turns} user turns.")
    if meta.get("source"):
        out.append("")
        out.append(f"**Provenance.** {meta['source']}")
    out.append("")
    out.append(f"Each section below gives the case metadata and the {n_turns} scripted "
               "user turns, verbatim and in the order used by the experiment. Nothing is "
               "paraphrased or added; the chatbot's replies are not part of the case set.")
    out.append("")

    for case in cases:
        out.append("---")
        out.append("")
        out.append(f"## {case['name']}")
        out.append("")
        out.append("| Field | Value |")
        out.append("|---|---|")
        out.append(f"| `id` | `{case['id']}` |")
        out.append(f"| `name` | {case['name']} |")
        out.append(f"| `theme` | {case['theme']} |")
        if case.get("theme_norm"):
            out.append(f"| `theme_norm` | {case['theme_norm']} |")
        out.append(f"| `condition` | {case['condition']} |")
        out.append(f"| `harm_type` | {case['harm_type']} |")
        out.append(f"| `turns` | {len(case['prompts'])} |")
        out.append("")
        for t, prompt in enumerate(case["prompts"], 1):
            out.append(f"### Turn {t}")
            out.append("")
            out.append("\n".join("> " + ln if ln.strip() else ">" for ln in prompt.splitlines()))
            out.append("")
    out.append("---")
    out.append("")
    out.append(f"End of mirror — {len(cases)} cases, {len(cases) * n_turns} user turns.")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    data = json.loads(SRC.read_text(encoding="utf-8"))
    text = render(data)

    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current == text:
            print(f"OK: {OUT.relative_to(ROOT)} is up to date")
            return 0
        print(f"STALE: {OUT.relative_to(ROOT)} differs from test_cases.json", file=sys.stderr)
        return 1

    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data['cases'])} cases, "
          f"{len(text.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
